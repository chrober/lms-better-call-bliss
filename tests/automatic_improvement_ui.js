const assert = require('assert');
const fs = require('fs');
const vm = require('vm');

const template = fs.readFileSync('BetterCallBliss/HTML/EN/plugins/BetterCallBliss/index.html', 'utf8');
const start = template.indexOf('    function automaticImprovementState(');
const end = template.indexOf('    function synchronizeControls()', start);
assert(start >= 0 && end > start, 'automatic improvement state is available');
const context = {};
vm.runInNewContext(template.slice(start, end), context);
const state = context.automaticImprovementState;
assert.strictEqual(state(true, true, false).showThreshold, false);
assert.strictEqual(state(true, false, true).showThreshold, true);
assert.strictEqual(state(true, false, false).invalid, true);
assert.strictEqual(state(true, true, true).invalid, false);
assert.strictEqual(state(false, false, false).invalid, false);
assert.strictEqual(state(true, true, false, false).invalid, true, 'disabled repeat rules do not count spacing as a goal');
assert.strictEqual(state(true, true, true, false).invalid, false, 'smoothing remains usable without repeat rules');
assert.strictEqual(state(true, true, false, true).invalid, false, 'spacing becomes effective again when repeat rules are enabled');
const control = {checked: true, disabled: false};
const saved = {value: ''};
const label = {classList: {toggle(_name, value) { label.muted = value; }}};
context.updateSpacingGoal(control, saved, label, false);
assert.strictEqual(control.disabled, true, 'spacing checkbox is disabled immediately');
assert.strictEqual(control.checked, false, 'disabled spacing checkbox is visibly unchecked');
assert.strictEqual(saved.value, '1', 'selection remains submit-ready when disabled');
assert.strictEqual(label.muted, true, 'disabled spacing label is muted');
context.updateSpacingGoal(control, saved, label, false);
assert.strictEqual(saved.value, '1', 'repeated updates retain the original selection');
context.updateSpacingGoal(control, saved, label, true);
assert.strictEqual(control.disabled, false, 're-enabling rules restores the checkbox');
assert.strictEqual(control.checked, true, 'previous selection remains checked');
control.checked = false;
context.updateSpacingGoal(control, saved, label, false);
context.updateSpacingGoal(control, saved, label, true);
assert.strictEqual(control.checked, false, 'a previously unchecked selection remains unchecked');
console.log('PASS: automatic improvement goal controls');
